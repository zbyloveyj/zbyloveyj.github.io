'use strict';
const assert=require('node:assert/strict'),M=require('../assets/lab-model.js');
const source='https://example.edu/lab/research';
const lab={name:'José Example',directions:['微生物组'],facets:{methods:['宏基因组学'],diseases:[],modalities:['宏基因组']},assessmentEvidence:[{dimension:'research',summary:'Research evidence',url:source},{dimension:'research',summary:'Second research source',url:source}]};
assert(M.searchText(lab).includes('jose'));
assert(M.matchesFacets(lab,{domains:'微生物组',methods:'宏基因组学'}));
assert(!M.matchesFacets(lab,{domains:'微生物组',diseases:'抑郁症'}));
assert.equal(M.evidenceCount(lab),1,'Two sources in one dimension are still one documented dimension.');
let match=M.match(lab,{domains:{value:'微生物组',weight:3},methods:{value:'宏基因组学',weight:1},diseases:{value:'抑郁症',weight:2},modalities:{value:'fMRI',weight:0}});
assert.equal(match.score,67);assert.equal(match.criteriaCount,3);assert.equal(match.missing[0].recorded,false);
assert.equal(M.match(lab,{}).score,null);
assert.equal(M.match(lab,{domains:{value:'微生物组',weight:0}}).score,null);
const entry={id:'example-1',name:'Example',saved:true,stage:'reading',note:'A private note <script>must remain text</script>',updatedAt:'2026-10-21T08:00:00Z'};
const file={type:M.notebookType,schemaVersion:1,entries:[entry]};
assert.deepEqual(M.validateNotebook(file),file);
const newer={...entry,note:'New note',updatedAt:'2026-10-21T10:00:00Z'};
assert.equal(M.mergeNotebooks({ ...file,entries:[newer]},file).entries[0].note,'New note');
assert.equal(M.mergeNotebooks(file,{...file,entries:[newer]}).entries[0].note,'New note');
assert.throws(()=>M.validateNotebook({...file,entries:[entry,entry]}));
assert.throws(()=>M.validateNotebook({...file,entries:[{...entry,id:'__proto__'}]}));
assert.throws(()=>M.validateNotebook({...file,entries:[{...entry,note:'x'.repeat(3001)}]}));
assert.throws(()=>M.validateNotebook({...file,entries:[{...entry,stage:'made-up'}]}));
assert.throws(()=>M.validateNotebook({...file,entries:[{...entry,updatedAt:'not-a-date'}]}));
assert.throws(()=>M.validateNotebook({entries:[entry]}));
const largeNotebook={...file,entries:Array.from({length:10001},(_,i)=>({...entry,id:'example-'+i}))};
assert.equal(M.validateNotebook(largeNotebook).entries.length,10001,'A directory with over ten thousand candidates must support a complete private backup.');
assert.equal(M.mergeNotebooks(file,largeNotebook).entries.length,10001);
// Old version-1 backups remain valid; optional plans and named views round-trip.
const plannedEntry={...entry,nextAction:'Read the public methods, then verify visiting eligibility',reviewDate:'2026-10-23'};
const view={id:'view-example',name:'欧洲微生物组',query:'country=%E5%BE%B7%E5%9B%BD&direction=%E5%BE%AE%E7%94%9F%E7%89%A9%E7%BB%84&weight-domains=3',updatedAt:'2026-10-21T11:00:00Z',deleted:false};
const plannedFile={...file,entries:[plannedEntry],savedViews:[view]};
assert.deepEqual(M.validateNotebook(plannedFile),plannedFile);
assert.deepEqual(M.mergeNotebooks(plannedFile,file).savedViews,[view]);
assert.throws(()=>M.validateNotebook({...file,entries:[{...plannedEntry,reviewDate:'2026-02-30'}]}));
assert.throws(()=>M.validateNotebook({...file,entries:[{...plannedEntry,reviewDate:'invalid'}]}));
assert.throws(()=>M.validateNotebook({...file,entries:[{...plannedEntry,nextAction:'x'.repeat(401)}]}));
assert.throws(()=>M.validateViews([{...view,query:'note=private'}]));
assert.throws(()=>M.validateViews([{...view,id:'__proto__'}]));
const removed={...view,deleted:true,updatedAt:'2026-10-21T12:00:00Z'};
assert.deepEqual(M.mergeViews([removed],[view]),[removed],'An older tab or backup cannot resurrect a deleted view.');
assert.deepEqual(M.mergeViews([view],[removed]),[removed]);
assert.equal(M.mergeNotebooks(file,{...plannedFile,entries:[{...plannedEntry,updatedAt:'2026-10-21T12:00:00Z'}]}).entries[0].reviewDate,'2026-10-23');
const newerLegacy={...entry,note:'Edited in an older tab',updatedAt:'2026-10-21T15:00:00Z'};
assert.equal(M.mergeNotebooks(plannedFile,{...file,entries:[newerLegacy]}).entries[0].reviewDate,'2026-10-23','A legacy backup or tab cannot erase fields it does not understand.');
assert.equal(M.mergeNotebooks({...file,entries:[newerLegacy]},plannedFile).entries[0].reviewDate,'2026-10-23','Newly understood fields also survive when the legacy record is the newer current side.');
assert.equal(M.mergeNotebooks(plannedFile,{...file,entries:[{...newerLegacy,nextAction:'',reviewDate:''}]}).entries[0].reviewDate,'','An explicit clear remains a real edit.');
console.log('Research model QA passed: cross-axis AND filters, explicit missing data, weighted tag coverage, evidence dimensions, private backup validation and newest-entry merge.');
